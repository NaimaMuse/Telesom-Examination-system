const assert = require('assert');
const { calculatePerformance, filterPerformanceReport, enrollmentBatch } = require('../services/teacherPerformanceService');
const course = { _id: 'c1', courseCode: 'CCNA', title: 'Cisco Network Associate' };
const assessments = [10, 10, 30, 50].map((maximum, index) => ({ _id: `a${index}`, title: index < 2 ? `Quiz ${index + 1}` : `Exam ${index}`, storageType: index < 2 ? 'quiz' : 'exam', assessmentType: index < 2 ? 'quiz' : 'exam', totalMarks: maximum, passingMarks: maximum / 2 }));
const enrollments = ['s1', 's2', 's3', 's1'].map(id => ({ academicYear: '2026-2027', student: { _id: id, studentId: id, academicYear: '2025-2026', user: { name: id } } }));
const results = [8, 9, 25, 45].map((marksObtained, index) => ({ _id: `r${index}`, student: 's1', assessmentId: `a${index}`, storageType: index < 2 ? 'quiz' : 'exam', marksObtained }));
results.push({ _id: 's2quiz', student: 's2', assessmentId: 'a0', storageType: 'quiz', marksObtained: 0 });
const report = calculatePerformance({ course, assessments, enrollments, results });
let filtered = filterPerformanceReport(report);
assert.strictEqual(filtered.students.length, 3);
assert.strictEqual(filtered.students[0].totalMarks, 87);
assert.strictEqual(filtered.students[0].courseName, 'Cisco Network Associate');
assert.deepStrictEqual(filtered.students[0].batches, ['2025-2026']);
assert.strictEqual(filtered.students[0].assessmentResults.length, 4);
filtered = filterPerformanceReport(report, { assessmentId: 'quiz:a0' });
assert.strictEqual(filtered.students.length, 2, 'Zero-mark participants must remain visible');
assert.strictEqual(filtered.students[0].filteredMarks, 8);
assert.strictEqual(filtered.students[0].filteredMaximum, 10);
assert.strictEqual(filtered.students[0].totalMarks, 87);
assert.strictEqual(filtered.students[0].assessmentResults.length, 4, 'Popup includes exams outside quiz filter');
assert.strictEqual(filtered.students[1].filteredMarks, 0);
filtered = filterPerformanceReport(report, { assessmentId: 'quiz:a1' });
assert.strictEqual(filtered.students.length, 1);
assert.strictEqual(filtered.students[0].filteredMarks, 9);
filtered = filterPerformanceReport(report, { type: 'exam' });
assert.strictEqual(filtered.students.length, 1);
assert.strictEqual(filtered.students[0].filteredMarks, 70);
assert.strictEqual(filtered.students[0].filteredMaximum, 80);
filtered = filterPerformanceReport(report, { type: 'quiz', search: 's2' });
assert.strictEqual(filtered.students.length, 1);
assert.strictEqual(filtered.students[0]._id, 's2');
assert.strictEqual(enrollmentBatch({ academicYear: '2026', student: { academicYear: '2025' } }), '2025');
assert.strictEqual(enrollmentBatch({ academicYear: '2026', student: {} }), '2026');
console.log('Performance student record tests passed: one row per student, full course totals, participant-only assessment filters, popup details and batch identity.');
